import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { shopifyFetch } from "../lib/shopify";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

const getProductsQuery = `
  query {
    products(first: 3) {
      edges {
        node {
          id
          title
          handle
        }
      }
    }
  }
`;

export default async function Home() {
  const data = await shopifyFetch({ query: getProductsQuery });
  const products = data.products.edges;

  return (
    <main className="p-8">
      <h1 className="text-3xl font-bold mb-6">Our Products</h1>
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        {products.map(({ node }: any) => (
          <div
            key={node.id}
            className="border border-gray-200 p-4 rounded shadow-sm"
          >
            <h2 className="text-xl font-semibold">{node.title}</h2>
            <p className="text-gray-600 mt-2">URL Handle: {node.handle}</p>
          </div>
        ))}
      </div>
    </main>
  );
}
